const INDEX = new Map(CARD_NUMBERS.map((number, index) => [number, index + 1]));

/** Embedding rows: one per card number plus the "no card" row. */
export const CARD_INDEX_SIZE = CARD_NUMBERS.length + 1;

/** The embedding index of a card id (0 for no card or an unknown one). */
export function cardIndex(ctx: EngineContext, cardId: string | null | undefined): number {
  const number = cardId ? ctx.card(cardId)?.number : undefined;
  return number ? INDEX.get(number) ?? 0 : 0;
}
